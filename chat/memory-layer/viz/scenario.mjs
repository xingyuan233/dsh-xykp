export function genTurns(n) {
  let seed = 20261107
  const rnd = () => (seed = (seed * 1103515245 + 12345) % 2147483648) / 2147483648
  const out = []
  for (let i = 0; i < n; i++) {
    const theme = POOL[Math.floor(rnd() * POOL.length)]
    const k = 2 + Math.floor(rnd() * 2)
    const picked = new Set()
    while (picked.size < k) picked.add(theme[Math.floor(rnd() * theme.length)])
    const words = [...picked]
    out.push({
      u: words[0],
      write: [{ brief: words.join('、') + ' —— 第 ' + (i + 1) + ' 天的日常', c: words.map((w) => [w, 0.45 + rnd() * 0.45]) }],
      r: rnd() < 0.6 ? words.join('和') + '都记得' : '嗯',
    })
  }
  return out
}

